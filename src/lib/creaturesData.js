// Check if a period overlaps with a creature's range
export function creatureOverlapsPeriod(creature, period) {
  // Overlap: creature existed during some of the period
  return creature.start_ma > period.end_ma && creature.end_ma < period.start_ma;
}

export function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}